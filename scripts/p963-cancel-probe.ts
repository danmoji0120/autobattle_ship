import { WorldSim } from '../src/world/sim';
import { FACILITIES, TECHS } from '../src/world/industry';
import { allocate } from '../src/world/construction';
import { storageCap } from '../src/world/production';
import { storeUsed } from '../src/world/storage';
import type { Station } from '../src/world/types';
import { strict as assert } from 'node:assert';
const sim = WorldSim.create(9638), p = sim.addPlayer('cancel probe');
sim.st.companies[p].credits = 10_000_000; sim.st.companies[p].tech = Object.keys(TECHS);
const base = sim.st.stations.astra;
const st: Station = { ...structuredClone(base), id: 'probe', owner: p, public: false, market: null, size: 'XL' as const, storage: { [p]: {} }, modules: ['core','yard_s','yard_m','yard_l'].map((kind, slot) => ({kind, slot, built: true, progress: 1})) };
sim.st.stations.probe = st;
const err = sim.command(p,{c:'queueModule',station:st.id,kind:'yard_xl'}); if (err) throw Error(err);
const plan = st.modules.at(-1) as any, inventory = st.storage[p] as Record<string,number>;
inventory.alloy = 70000; allocate(st, inventory); Object.assign(inventory, {...FACILITIES.yard_xl.mats, alloy:0}); allocate(st, inventory);
const reserved = Object.values(plan.reserved as Record<string,number>).reduce((a,b)=>a+b,0);
const result = sim.command(p,{c:'planOp',station:st.id,plan:plan.id,op:'cancel'}); if(result) throw Error(result);
assert.equal(reserved, 81_850); assert.equal(storeUsed(inventory), reserved); assert.equal(storageCap(st), 80_000); assert.equal(sim.st.companies[p].credits, 10_000_000);
console.log(JSON.stringify({reserved, returned:storeUsed(inventory), capacity:storageCap(st), credits:sim.st.companies[p].credits, preserved:reserved===storeUsed(inventory)}));
